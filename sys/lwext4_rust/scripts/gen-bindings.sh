#!/bin/sh
# Regenerate src/bindings.rs. Needs `bindgen` (cargo install bindgen-cli) and
# libclang. The result is committed, so normal builds do not need either.
#
# All three kernel targets are LP64 little-endian, so one binding file is
# valid for x86_64, aarch64 and riscv64 (the layout tests in the generated
# file check this on the host).
set -e
cd "$(dirname "$0")/.."
bindgen c/wrapper.h \
    --use-core --ctypes-prefix core::ffi \
    --no-doc-comments --no-prepend-enum-name \
    --allowlist-function 'ext4_.*' \
    --allowlist-type 'ext4_.*' \
    --allowlist-var '(EXT4_.*|DEBUG_.*|E[A-Z0-9]+|O_[A-Z]+|SEEK_(SET|CUR|END))' \
    --raw-line '// @generated by scripts/gen-bindings.sh -- do not edit by hand.' \
    --raw-line '#![allow(clippy::all, dead_code, unused)]' \
    -o src/bindings.rs \
    -- --target=x86_64-unknown-none-elf -ffreestanding -nostdlibinc \
       -isystem c/include -Ic/lwext4/include $(cat c/config.txt)
