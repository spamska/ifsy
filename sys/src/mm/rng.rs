#[derive(Clone, Debug)]
pub struct Rng {
    s: [u64; 4],
    pub hardware_seeded: bool,
}

fn splitmix64(state: &mut u64) -> u64 {
    *state = state.wrapping_add(0x9E37_79B9_7F4A_7C15);
    let mut z = *state;
    z = (z ^ (z >> 30)).wrapping_mul(0xBF58_476D_1CE4_E5B9);
    z = (z ^ (z >> 27)).wrapping_mul(0x94D0_49BB_1331_11EB);
    z ^ (z >> 31)
}

impl Rng {
    pub fn from_seed(seed: u64) -> Self {
        let mut sm = seed;
        let s = [splitmix64(&mut sm), splitmix64(&mut sm), splitmix64(&mut sm), splitmix64(&mut sm)];
        Self { s, hardware_seeded: false }
    }

    pub fn from_entropy() -> Self {
        let mut acc = 0u64;
        let mut hw = true;
        for i in 0..4u64 {
            let (v, is_hw) = super::hw::entropy();
            hw &= is_hw;
            acc = acc.rotate_left(17) ^ v ^ i.wrapping_mul(0x9E37_79B9_7F4A_7C15);
        }
        let mut r = Self::from_seed(acc);
        r.hardware_seeded = hw;
        r
    }

    pub fn next_u64(&mut self) -> u64 {
        let r = self.s[1].wrapping_mul(5).rotate_left(7).wrapping_mul(9);
        let t = self.s[1] << 17;
        self.s[2] ^= self.s[0];
        self.s[3] ^= self.s[1];
        self.s[1] ^= self.s[2];
        self.s[0] ^= self.s[3];
        self.s[2] ^= t;
        self.s[3] = self.s[3].rotate_left(45);
        r
    }

    pub fn below(&mut self, bound: u64) -> u64 {
        if bound <= 1 {
            return 0;
        }
        let zone = u64::MAX - (u64::MAX % bound);
        loop {
            let v = self.next_u64();
            if v < zone {
                return v % bound;
            }
        }
    }

    pub fn aligned_below(&mut self, span: u64, align: u64) -> u64 {
        self.below(span / align) * align
    }

    pub fn fork(&mut self) -> Self {
        let mut r = Self::from_seed(self.next_u64() ^ self.next_u64().rotate_left(32));
        r.hardware_seeded = self.hardware_seeded;
        r
    }
}
