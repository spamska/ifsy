.text
.globl	setjmp
.type	setjmp,@function
setjmp:
	leaq	8(%rsp), %rax
	movq	%rax, 0(%rdi)
	movq	(%rsp), %rax
	movq	%rax, 8(%rdi)
	movq	%rbx, 16(%rdi)
	movq	%rbp, 24(%rdi)
	movq	%r12, 32(%rdi)
	movq	%r13, 40(%rdi)
	movq	%r14, 48(%rdi)
	movq	%r15, 56(%rdi)
	xorl	%eax, %eax
	ret

.globl	longjmp
.type	longjmp,@function
longjmp:
	movl	%esi, %eax
	testl	%eax, %eax
	jnz	1f
	incl	%eax
1:
	movq	16(%rdi), %rbx
	movq	24(%rdi), %rbp
	movq	32(%rdi), %r12
	movq	40(%rdi), %r13
	movq	48(%rdi), %r14
	movq	56(%rdi), %r15
	movq	0(%rdi), %rsp
	jmp	*8(%rdi)
	.section .note.GNU-stack,"",@progbits
